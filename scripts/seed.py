def seed() -> None:
    for folder in ("companies", "models", "founders", "countries", "news", "funding", "benchmarks", "research"):
        (DATA / folder).mkdir(parents=True, exist_ok=True)

    write(DATA / "countries" / "regions.json", REGIONS)
    for country in COUNTRIES:
        record = {
            **country,
            "activityScore": 0,
            "companyCount": 0,
            "modelCount": 0,
        }
        write(DATA / "countries" / f"{country['id'].lower()}.json", record)

    for founder in FOUNDERS:
        write(DATA / "founders" / f"{founder['id']}.json", founder)

    for company in COMPANIES:
        # Fix moonshot research areas if the ternary left a bad value
        if company["id"] == "moonshot":
            company["researchAreaIds"] = ["reasoning", "agents", "multimodal"]
        write(DATA / "companies" / f"{company['id']}.json", company)

    for model in MODELS:
        write(DATA / "models" / f"{model['id']}.json", model)

    for row in FUNDING:
        write(DATA / "funding" / f"{row['id']}.json", row)

    for item in NEWS:
        write(DATA / "news" / f"{item['id']}.json", item)

    (DATA / "news" / "generated").mkdir(parents=True, exist_ok=True)
    (DATA / "news" / "generated" / ".gitkeep").write_text("", encoding="utf-8")

    for bench in BENCHMARKS:
        write(DATA / "benchmarks" / f"{bench['id']}.json", bench)
    write(DATA / "benchmarks" / "scores.json", SCORES)

    for area in RESEARCH_AREAS:
        write(DATA / "research" / f"{area['id']}.json", area)
    for lab in LABS:
        write(DATA / "research" / f"{lab['id']}.json", lab)

    logos = PUBLIC / "logos"
    avatars = PUBLIC / "avatars"
    logos.mkdir(parents=True, exist_ok=True)
    avatars.mkdir(parents=True, exist_ok=True)
    for key, (text, bg) in LOGOS.items():
        (logos / f"{key}.svg").write_text(svg_mark(text, bg, "#f8fafc" if bg != "#e8eaed" else "#111111"), encoding="utf-8")
    (logos / "xai.svg").write_text(svg_mark("x", "#111111", "#f8fafc"), encoding="utf-8")
    for key, (text, bg) in AVATARS.items():
        (avatars / f"{key}.svg").write_text(svg_avatar(text, bg), encoding="utf-8")

    print(f"Seeded {len(COMPANIES)} companies, {len(MODELS)} models, {len(FOUNDERS)} founders.")


if __name__ == "__main__":
    seed()
